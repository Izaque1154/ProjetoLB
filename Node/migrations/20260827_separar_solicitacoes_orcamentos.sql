-- Separa os dados enviados pelo cliente dos orçamentos montados pelo admin.
--
-- Esta migração é deliberadamente aditiva: os campos legados continuam em
-- "orcamentos" (agora nullable) para permitir uma transição segura do código.
-- Execute com a aplicação parada e com psql configurado para ON_ERROR_STOP.

BEGIN;

-- Evita aguardar indefinidamente caso a aplicação ainda esteja usando as tabelas.
SET LOCAL lock_timeout = '10s';

LOCK TABLE "orcamentos", "orçamentoItens" IN SHARE ROW EXCLUSIVE MODE;

-- A solicitação preserva todos os dados que o formulário atual já envia.
-- produtoId é mantido como campo legado opcional para que nenhum dado antigo
-- seja descartado; o formulário atual utiliza principalmente servicoId.
CREATE TABLE IF NOT EXISTS "solicitacoes_orcamento" (
    "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "usuarioId" INTEGER NOT NULL,
    "produtoId" INTEGER NULL,
    "servicoId" INTEGER NULL,
    "nome" VARCHAR(255) NOT NULL,
    "telefone" VARCHAR(255) NOT NULL,
    "veiculo" VARCHAR(255) NOT NULL,
    "placa" VARCHAR(255) NULL,
    "chassi" VARCHAR(255) NULL,
    "quilometragem" INTEGER NULL,
    "descricao" TEXT NOT NULL,
    "urgencia" VARCHAR(255) NOT NULL,
    "foto" VARCHAR(255) NULL,
    "status" VARCHAR(255) NOT NULL DEFAULT 'novo',
    "createdAt" TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "solicitacoes_orcamento_usuarioId_fkey"
        FOREIGN KEY ("usuarioId") REFERENCES "usuarios" ("id")
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT "solicitacoes_orcamento_produtoId_fkey"
        FOREIGN KEY ("produtoId") REFERENCES "produtos" ("id")
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT "solicitacoes_orcamento_servicoId_fkey"
        FOREIGN KEY ("servicoId") REFERENCES "servicos" ("id")
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT "solicitacoes_orcamento_status_check"
        CHECK ("status" IN (
            'novo',
            'em analise',
            'respondido',
            'aguardando resposta',
            'finalizado'
        )),
    CONSTRAINT "solicitacoes_orcamento_quilometragem_check"
        CHECK ("quilometragem" IS NULL OR "quilometragem" >= 0)
);

COMMENT ON TABLE "solicitacoes_orcamento" IS
    'Solicitações enviadas pelos clientes antes da criação de um orçamento pelo admin.';

-- As colunas são adicionadas antes do backfill. IF NOT EXISTS permite repetir
-- a migração depois de uma execução já concluída sem recriá-las.
ALTER TABLE "orcamentos"
    ADD COLUMN IF NOT EXISTS "solicitacaoId" INTEGER,
    ADD COLUMN IF NOT EXISTS "valorTotal" NUMERIC(12, 2),
    ADD COLUMN IF NOT EXISTS "validade" DATE;

-- Interrompe em vez de converter silenciosamente um status desconhecido.
-- A única normalização necessária nos dados atuais é "em análise" ->
-- "em analise", mantendo a lista já utilizada pelo projeto.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM "orcamentos" AS o
        WHERE o."solicitacaoId" IS NULL
          AND CASE LOWER(BTRIM(o."status"))
                WHEN 'novo' THEN 'novo'
                WHEN 'em analise' THEN 'em analise'
                WHEN 'em análise' THEN 'em analise'
                WHEN 'respondido' THEN 'respondido'
                WHEN 'aguardando resposta' THEN 'aguardando resposta'
                WHEN 'finalizado' THEN 'finalizado'
                ELSE NULL
              END IS NULL
    ) THEN
        RAISE EXCEPTION
            'Existem orçamentos com status não suportado. Corrija-os antes de executar a migração.';
    END IF;
END
$$;

-- Cada orçamento legado representa, ao mesmo tempo, a solicitação original e
-- o orçamento já montado. A cópia mantém id, usuário, dados e timestamps.
INSERT INTO "solicitacoes_orcamento" (
    "id",
    "usuarioId",
    "produtoId",
    "servicoId",
    "nome",
    "telefone",
    "veiculo",
    "placa",
    "chassi",
    "quilometragem",
    "descricao",
    "urgencia",
    "foto",
    "status",
    "createdAt",
    "updatedAt"
)
SELECT
    o."id",
    o."usuarioId",
    o."produtoId",
    o."servicoId",
    o."nome",
    o."telefone",
    o."veiculo",
    o."placa",
    o."chassi",
    o."quilometragem",
    o."descricao",
    o."urgencia",
    o."foto",
    CASE LOWER(BTRIM(o."status"))
        WHEN 'novo' THEN 'novo'
        WHEN 'em analise' THEN 'em analise'
        WHEN 'em análise' THEN 'em analise'
        WHEN 'respondido' THEN 'respondido'
        WHEN 'aguardando resposta' THEN 'aguardando resposta'
        WHEN 'finalizado' THEN 'finalizado'
    END,
    o."createdAt",
    o."updatedAt"
FROM "orcamentos" AS o
WHERE o."solicitacaoId" IS NULL
ON CONFLICT ("id") DO NOTHING;

-- Liga apenas registros compatíveis. Se já existir uma solicitação com o mesmo
-- id para outro usuário, a validação abaixo abortará toda a transação.
UPDATE "orcamentos" AS o
SET "solicitacaoId" = o."id"
FROM "solicitacoes_orcamento" AS s
WHERE o."solicitacaoId" IS NULL
  AND s."id" = o."id"
  AND s."usuarioId" = o."usuarioId";

-- Como os ids foram copiados explicitamente, reposiciona a identity para que a
-- próxima solicitação receba um id livre.
SELECT SETVAL(
    PG_GET_SERIAL_SEQUENCE('solicitacoes_orcamento', 'id'),
    COALESCE(MAX("id"), 1),
    MAX("id") IS NOT NULL
)
FROM "solicitacoes_orcamento";

-- O valor total antigo era virtual no Sequelize. Ele passa a ser persistido no
-- orçamento e é calculado exclusivamente a partir dos itens existentes.
WITH totais AS (
    SELECT
        i."orcamentoId",
        ROUND(SUM(
            (i."quantidade"::NUMERIC * i."precoUnitario")
            - COALESCE(i."desconto", 0)
            + COALESCE(i."frete", 0)
        ), 2)::NUMERIC(12, 2) AS "valorTotal"
    FROM "orçamentoItens" AS i
    GROUP BY i."orcamentoId"
)
UPDATE "orcamentos" AS o
SET "valorTotal" = t."valorTotal"
FROM totais AS t
WHERE o."id" = t."orcamentoId"
  AND o."valorTotal" IS NULL;

UPDATE "orcamentos"
SET "valorTotal" = 0
WHERE "valorTotal" IS NULL;

-- Valida o backfill antes de tornar a relação obrigatória.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM "orcamentos"
        WHERE "solicitacaoId" IS NULL
    ) THEN
        RAISE EXCEPTION
            'Não foi possível relacionar todos os orçamentos a uma solicitação.';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM "orcamentos" AS o
        LEFT JOIN "solicitacoes_orcamento" AS s
          ON s."id" = o."solicitacaoId"
        WHERE s."id" IS NULL
    ) THEN
        RAISE EXCEPTION
            'Foi encontrada uma referência de solicitação inválida em orcamentos.';
    END IF;

    IF EXISTS (
        SELECT "solicitacaoId"
        FROM "orcamentos"
        GROUP BY "solicitacaoId"
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION
            'Mais de um orçamento está ligado à mesma solicitação.';
    END IF;
END
$$;

ALTER TABLE "orcamentos"
    ALTER COLUMN "solicitacaoId" SET NOT NULL,
    ALTER COLUMN "valorTotal" SET DEFAULT 0,
    ALTER COLUMN "valorTotal" SET NOT NULL;

-- A constraint UNIQUE materializa a cardinalidade 1:0..1 entre solicitação e
-- orçamento. Os blocos condicionais evitam duplicá-la em uma nova execução.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'orcamentos'::regclass
          AND conname = 'orcamentos_solicitacaoId_key'
    ) THEN
        ALTER TABLE "orcamentos"
            ADD CONSTRAINT "orcamentos_solicitacaoId_key"
            UNIQUE ("solicitacaoId");
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'orcamentos'::regclass
          AND conname = 'orcamentos_solicitacaoId_fkey'
    ) THEN
        ALTER TABLE "orcamentos"
            ADD CONSTRAINT "orcamentos_solicitacaoId_fkey"
            FOREIGN KEY ("solicitacaoId")
            REFERENCES "solicitacoes_orcamento" ("id")
            ON UPDATE CASCADE
            ON DELETE RESTRICT
            NOT VALID;
    END IF;
END
$$;

ALTER TABLE "orcamentos"
    VALIDATE CONSTRAINT "orcamentos_solicitacaoId_fkey";

-- Permite que os novos orçamentos contenham somente dados administrativos.
-- As colunas não são removidas nesta entrega para manter compatibilidade e
-- facilitar uma eventual conferência/recuperação dos dados antigos.
ALTER TABLE "orcamentos"
    ALTER COLUMN "nome" DROP NOT NULL,
    ALTER COLUMN "telefone" DROP NOT NULL,
    ALTER COLUMN "veiculo" DROP NOT NULL,
    ALTER COLUMN "descricao" DROP NOT NULL,
    ALTER COLUMN "urgencia" DROP NOT NULL;

-- Produto e serviço são referências opcionais do item. SET NULL preserva o
-- histórico e os valores/descrição do orçamento caso um cadastro seja removido.
ALTER TABLE "orçamentoItens"
    ALTER COLUMN "produtoId" DROP NOT NULL,
    ALTER COLUMN "servicoId" DROP NOT NULL,
    DROP CONSTRAINT IF EXISTS "orçamentoItens_produtoId_fkey",
    DROP CONSTRAINT IF EXISTS "orçamentoItens_servicoId_fkey";

ALTER TABLE "orçamentoItens"
    ADD CONSTRAINT "orçamentoItens_produtoId_fkey"
        FOREIGN KEY ("produtoId") REFERENCES "produtos" ("id")
        ON UPDATE CASCADE ON DELETE SET NULL,
    ADD CONSTRAINT "orçamentoItens_servicoId_fkey"
        FOREIGN KEY ("servicoId") REFERENCES "servicos" ("id")
        ON UPDATE CASCADE ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS "solicitacoes_orcamento_usuarioId_idx"
    ON "solicitacoes_orcamento" ("usuarioId");

CREATE INDEX IF NOT EXISTS "solicitacoes_orcamento_status_createdAt_idx"
    ON "solicitacoes_orcamento" ("status", "createdAt" DESC);

CREATE INDEX IF NOT EXISTS "orcamentos_usuarioId_idx"
    ON "orcamentos" ("usuarioId");

CREATE INDEX IF NOT EXISTS "orcamentos_status_createdAt_idx"
    ON "orcamentos" ("status", "createdAt" DESC);

COMMENT ON COLUMN "orcamentos"."solicitacaoId" IS
    'Solicitação que originou o orçamento; relação obrigatória e única.';
COMMENT ON COLUMN "orcamentos"."valorTotal" IS
    'Total calculado no backend a partir dos itens do orçamento.';
COMMENT ON COLUMN "orcamentos"."validade" IS
    'Data limite de validade comercial do orçamento.';

COMMIT;
